"""Run one bounded calibration/round at a time; publish checked comparison CSVs."""
import argparse
import csv
import hashlib
import json
import math
import os
from pathlib import Path
import random
import signal
import statistics
import subprocess
import sys
import time
from types import SimpleNamespace

from fixtures import CASES, encode, fixture, oracle
from runner import ROOT, Child, digest, load_record, metadata
from service import measure, window_metrics

RUN = ROOT/'results/baseline-2026-09-29'
VARIANTS = [('baml','medium'), ('baml','off'), ('rust','none'), ('go','none'),
            ('python','none'), ('node','none'), ('bun','none')]
CPUS = [15,16]
CLIENT_CPU = 5
TRIALS = 5
SCENARIOS = {
    '00_startup': {'constant': {'size':1}},
    '01_array_traversal': {v: {'size':65536,'variant':v} for v in ('iterator','indexed','build')},
    '02_merge_sort': {v: {'size':4096,'variant':v} for v in ('random','duplicates')},
    '03_json_aggregate': {'1000_records': {'size':1000}, '10000_records': {'size':10000}},
    '04_allocation_retention': {f'retain_{n}': {'size':256,'batches':128,'retain':n} for n in (0,4,32)},
    '05_async_fanout': {f'fanout_{n}': {'size':256,'fanout':n,'delay_ms':10} for n in (8,32)},
    '06_http_service': {f'{r}_rps': {'size':100,'rate':r,'requests':1000} for r in (100,500)},
}


def write_json(path, data):
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(json.dumps(data,indent=2)+'\n')


def config(case, scenario):
    parameters = SCENARIOS[case][scenario]
    raw = fixture(case,**{k:v for k,v in parameters.items() if k not in ('rate','requests')})
    return parameters,raw,oracle(case,raw)


def record_for(case,language):
    record = load_record(case,language).copy()
    record['cpu_affinity'] = CPUS
    return record


def file_inventory(paths):
    unique = {Path(p).resolve() for p in paths if Path(p).is_file()}
    return [{'path':str(p),'bytes':p.stat().st_size,'sha256':digest(p)} for p in sorted(unique)]


def inventory(case, language, record, pid):
    executable = Path(record['command'][0]).resolve()
    mapped = set()
    for line in Path(f'/proc/{pid}/maps').read_text().splitlines():
        parts = line.split(maxsplit=5)
        if len(parts) == 6 and parts[5].startswith('/'):
            mapped.add(Path(parts[5]).resolve())
    # Record the bundle explicitly; do not compare a script with a standalone ELF.
    if language in ('baml','go','rust'):
        application = {executable}
        runtime = set()
    else:
        application = {ROOT/p for p in record['source_hashes']}
        runtime = {executable}
        if language == 'python':
            settings = json.loads(subprocess.check_output([str(executable),'-c',
                'import json,sysconfig; print(json.dumps({k:sysconfig.get_path(k) for k in ("stdlib","purelib","platlib")}))'],text=True))
            # Full stdlib + installed HTTP dependencies; exclude generated bytecode.
            for root in set(settings.values()):
                for path in Path(root).rglob('*'):
                    if '__pycache__' not in path.parts and path.suffix not in ('.pyc','.pyo') and path.is_file():
                        runtime.add(path.resolve())
            # A venv's python resolves to the base executable; its dependencies live
            # under the original venv command, not under the resolved interpreter.
            venv = Path(record['command'][0]).parent.parent
            if (venv/'pyvenv.cfg').exists():
                for path in (venv/'lib').rglob('*'):
                    if '__pycache__' not in path.parts and path.suffix not in ('.pyc','.pyo') and path.is_file():
                        runtime.add(path.resolve())
    application = {p.resolve() for p in application}
    runtime -= application
    libraries = mapped - application - runtime
    groups = {k:file_inventory(v) for k,v in [('application',application),('runtime',runtime),('mapped_libraries',libraries)]}
    sizes = {f'{k}_bytes':sum(p['bytes'] for p in v) for k,v in groups.items()}
    sizes['bundle_bytes'] = sum(sizes.values())
    return {'sizes':sizes,'files':groups}


def calibrate(case, scenario):
    parameters,raw,expected = config(case,scenario)
    destination = RUN/case/scenario
    destination.mkdir(parents=True,exist_ok=True)
    (destination/'fixture.json').write_text(raw+'\n')
    calibration = {}
    for language,mode in VARIANTS:
        key = f'{language}-{mode}'
        record = record_for(case,language)
        if case == '06_http_service':
            # The timed server run will collect its loaded-library inventory.
            calibration[key] = {'jobs':parameters['requests'],'warmup':100}
            continue
        child = Child(record,raw,mode,destination/f'calibrate-{key}')
        try:
            child.ready()
            if case == '00_startup': jobs,warmup = 1,0
            else:
                child.batch(10,expected)
                pilot = child.batch(10,expected)
                # ~2s per trial, bounded by 32MiB of retained result text.
                output_cap = max(1,(32*1024*1024)//max(16,len(encode(expected))))
                jobs = min(100000,output_cap,max(5,math.ceil(2/pilot['wall_s']*10)))
                warmup = max(10,math.ceil(jobs/2))
            artifact = inventory(case,language,record,child.measure_pid)
            calibration[key] = {'jobs':jobs,'warmup':warmup,'artifact':artifact,'build':record}
            child.finish()
        except BaseException:
            child.abort()
            raise
        print(f'calibrated {case}/{scenario}/{key}: warmup={warmup}, jobs={jobs}',flush=True)
    write_json(destination/'calibration.json',calibration)


def compact_invocation(invocation):
    return {k:v for k,v in invocation.items() if k!='samples'}


def round_run(case,scenario,round_number):
    parameters,raw,expected = config(case,scenario)
    destination = RUN/case/scenario
    calibration = json.loads((destination/'calibration.json').read_text())
    order = VARIANTS.copy()
    random.Random(1729+round_number).shuffle(order)
    for language,mode in order:
        key = f'{language}-{mode}'
        trial = destination/f'round-{round_number}-{key}'
        output = trial/'result.json'
        if output.exists():
            print(f'already recorded {case}/{scenario}/{key}/{round_number}',flush=True)
            continue
        if trial.exists():
            trial.rename(trial.with_name(trial.name+f'-interrupted-{time.time_ns()}'))
        plan = calibration[key]
        record = record_for(case,language)
        started = time.strftime('%Y-%m-%dT%H:%M:%SZ',time.gmtime())
        load_before = os.getloadavg()
        if case == '06_http_service':
            settings = SimpleNamespace(warmup=100,rate=parameters['rate'],requests=parameters['requests'],
                                       deadline_ms=100,action='run')
            result = measure(record,raw,expected,mode,trial,settings,
                             on_ready=lambda pid: inventory(case,language,record,pid))
            artifact = result.pop('artifact')
        else:
            child = Child(record,raw,mode,trial)
            try:
                ready = child.ready()
                warm = child.batch(plan['warmup'],expected) if plan['warmup'] else None
                batch = child.batch(plan['jobs'],expected)
                invocation = child.finish()
                if case != '00_startup' and (batch['cpu_s'] <= 0 or batch['cpu_s'] > invocation['cpu_s'] + 0.02):
                    raise RuntimeError(f"phase CPU {batch['cpu_s']} inconsistent with invocation {invocation['cpu_s']}")
                result = {'ready_s':ready,'batch':batch,'invocation':invocation,'warmup':warm}
                artifact = plan['artifact']
            except BaseException:
                child.abort()
                raise
        result['invocation'] = compact_invocation(result['invocation'])
        for phase in ('batch','warmup'):
            if result.get(phase): result[phase].pop('completion_offsets_s',None)
        if 'http' in result:
            write_json(trial/'requests.json',result['http'].pop('requests'))
        result.update(case=case,scenario=scenario,parameters=parameters,language=language,
                      telemetry_requested=mode,round=round_number,timestamp_utc=started,
                      load_before=load_before,load_after=os.getloadavg(),
                      input_sha256=hashlib.sha256(raw.encode()).hexdigest(),
                      input_bytes=len(raw.encode()),artifact_sizes=artifact['sizes'],build=record)
        write_json(trial/'artifact.json',artifact)
        write_json(output,result)
        print(f'measured {case}/{scenario}/{key}/{round_number}',flush=True)


def median(rows,key):
    return statistics.median(row[key] for row in rows)


def publish():
    manifest = {'protocol': {'benchmark_cpus':CPUS,'client_cpu':CLIENT_CPU,'trials':TRIALS,
                 'batch_target_wall_s':2,'warmup':'half measured jobs, at least 10; HTTP 100 requests',
                 'max_retained_output_bytes':32*1024*1024,'seed':1729,
                 'http':'HTTP/1.1 connection close; no TLS; latency from scheduled arrival',
                 'gc':'runtime defaults; no forced collections',
                 'cpu':'Linux process CPU clock; all threads. Complete-invocation CPU from wait4.',
                 'rss':'wait4 from a small native observer; maximum over process trials',
                 'telemetry':'BAML requested medium/off; event policy not validated',
                 'builds':'installed BAML release; Rust release stripped; Go -s -w; Node/Bun prebuilt'},
                'machine':metadata(SimpleNamespace()),'scenarios':SCENARIOS,'builds':{},
                'published_harness_sources':{name:digest(ROOT/name) for name in
                                       ('baseline.py','runner.py','observer.c','service.py','fixtures.py')}}
    for case in CASES:
        summary,raw_rows = [],[]
        for scenario in SCENARIOS[case]:
            _,fixture_raw,_ = config(case,scenario)
            (RUN/case/scenario/'fixture.json').write_text(fixture_raw+'\n')
            normalized = {}
            for language,mode in VARIANTS:
                values = []
                provenance = None
                for n in range(TRIALS):
                    path = RUN/case/scenario/f'round-{n}-{language}-{mode}'/'result.json'
                    r = json.loads(path.read_text())
                    if r['input_sha256'] != hashlib.sha256(fixture_raw.encode()).hexdigest():
                        raise RuntimeError('fixture hash mismatch')
                    identity = (r['build']['executable_sha256'],r['build']['version'],r['build']['source_hashes'])
                    if provenance is not None and identity != provenance:
                        raise RuntimeError('mixed builds within one comparison row')
                    provenance = identity
                    manifest['builds'][f'{case}/{language}'] = r['build']
                    invocation = r['invocation']
                    row = {'scenario':scenario,'language':language,'telemetry_requested':mode,'round':n,
                           'process_cpu_ms':invocation['cpu_s']*1000,
                           'process_wall_ms':invocation['wall_s']*1000,
                           'peak_rss_mib':invocation['peak_rss_bytes']/1048576}
                    if case == '06_http_service':
                        h = r['http']
                        requests = json.loads(path.with_name('requests.json').read_text())
                        if len(requests) != h['offered'] or h['correct']+h['failed_or_incorrect'] != h['offered']:
                            raise RuntimeError('incomplete HTTP accounting')
                        h.update(window_metrics(requests,h['offered_rate_rps'],h['observed_window_s'],h['deadline_ms']))
                        if h['cpu_s'] < 0 or h['cpu_s'] > invocation['cpu_s']+.02:
                            raise RuntimeError('HTTP CPU accounting mismatch')
                        row.update(window_s=h['measurement_window_s'],drain_s=h['drain_s'],offered_rps=h['offered_rate_rps'],
                                   correct_rps=h['correct_rps'],goodput_rps=h['goodput_rps'],
                                   cpu_ms=h['cpu_s']*1000/h['correct'] if h['correct'] else None,
                                   p50_ms=h['p50_ms'],p95_ms=h['p95_ms'],p99_ms=h['p99_ms'],
                                   failures=h['failed_or_incorrect'],late=h['late_correct'],
                                   client_max_lag_ms=h['max_dispatch_lag_ms'],jobs=h['offered'])
                    elif case == '00_startup':
                        row.update(jobs=1,wall_ms=invocation['wall_s']*1000,cpu_ms=invocation['cpu_s']*1000,
                                   first_result_ms=invocation['first_correct_result_s']*1000)
                    else:
                        b = r['batch']
                        row.update(jobs=b['jobs'],wall_ms=b['wall_s']/b['jobs']*1000,
                                   cpu_ms=b['cpu_s']/b['jobs']*1000,batch_wall_s=b['wall_s'])
                    values.append(row)
                    raw_rows.append(row)
                normalized[(language,mode)] = values
                entry = {k:values[0][k] for k in ('scenario','language','telemetry_requested')}
                entry.update(runtime_version=r['build']['version'].splitlines()[0],
                             unit='request' if case=='06_http_service' else 'invocation' if case=='00_startup' else 'job',
                             trials=TRIALS,jobs_per_trial=values[0]['jobs'])
                for key in values[0]:
                    if key in ('scenario','language','telemetry_requested','round','jobs','peak_rss_mib'): continue
                    if key in ('process_cpu_ms','process_wall_ms'): continue
                    if key in ('failures','late'): entry[key] = sum(v[key] for v in values)
                    elif all(v[key] is not None for v in values): entry[key] = median(values,key)
                    else: entry[key] = None
                entry['cpu_min_ms'] = min(v['cpu_ms'] for v in values if v['cpu_ms'] is not None)
                entry['cpu_max_ms'] = max(v['cpu_ms'] for v in values if v['cpu_ms'] is not None)
                if 'wall_ms' in values[0]:
                    entry['wall_min_ms'] = min(v['wall_ms'] for v in values)
                    entry['wall_max_ms'] = max(v['wall_ms'] for v in values)
                if 'p99_ms' in values[0] and all(v['p99_ms'] is not None for v in values):
                    entry['p99_min_ms'] = min(v['p99_ms'] for v in values)
                    entry['p99_max_ms'] = max(v['p99_ms'] for v in values)
                entry['peak_rss_mib'] = max(v['peak_rss_mib'] for v in values)
                entry.update(r['artifact_sizes'])
                summary.append(entry)
            node = normalized[('node','none')]
            for entry in summary:
                if entry['scenario'] != scenario: continue
                entry['cpu_vs_node'] = entry['cpu_ms']/median(node,'cpu_ms')
                if 'wall_ms' in entry: entry['wall_vs_node'] = entry['wall_ms']/median(node,'wall_ms')
        for filename,rows in [('baseline.csv',summary),('baseline.samples.csv',raw_rows)]:
            with (ROOT/case/filename).open('w') as f:
                writer = csv.DictWriter(f,fieldnames=list(rows[0]),lineterminator='\n')
                writer.writeheader()
                for row in rows:
                    writer.writerow({k:round(v,6) if isinstance(v,float) else v for k,v in row.items()})
        print(f'published {case}/baseline.csv',flush=True)
    write_json(ROOT/'baseline.environment.json',manifest)


def main():
    global RUN
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('action',choices=('calibrate','round','publish'))
    p.add_argument('--case',choices=CASES)
    p.add_argument('--scenario')
    p.add_argument('--round',type=int,default=0)
    p.add_argument('--run-dir',type=Path,default=RUN)
    args = p.parse_args()
    RUN = args.run_dir.resolve()
    signal.signal(signal.SIGTERM,lambda *_: sys.exit(124))
    os.sched_setaffinity(0,{CLIENT_CPU})
    os.environ.update(GOMAXPROCS='2',TOKIO_WORKER_THREADS='2')
    if args.action == 'publish': publish()
    elif args.action == 'calibrate': calibrate(args.case,args.scenario)
    else: round_run(args.case,args.scenario,args.round)


if __name__ == '__main__': main()
